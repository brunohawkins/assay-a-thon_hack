"""Module 3, capsule wash (REAL scale, DRAFT): one capsule trap sized by operator/sizing.py.

    python cad/generators/m3_wash.py        # writes cad/m3_wash_spec.json

A single trap chamber holds 10,000 capsules (sizing.py "mvp" preset) as one layer on a
bought 25 um mesh. Liquid comes in from an inlet above, leaves through a waste outlet
below the mesh (capsules stay on top), and a back-flush inlet below the mesh pushes
liquid up to lift the capsules off it. A release outlet lets the resuspended capsules
out. Channels are 2 x capsule diameter wide. Side view (not to scale):

        m3_inlet_1                 m3_release_1
          |                            |
    lid   |                            |
    ======|===========+       +========|=====
    trap  |  o o o o o o o o o o o  ---+        <- 150 um high, capsules on the mesh
    ......:...........mesh (25 um)..........
    base  ---+                    +---
             |                    |
     m3_backflush_1           m3_waste_1        (bottom ports)

Edit the numbers below, then re-run. Don't hand-edit the JSON.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "operator"))

import schema_io  # noqa: E402
import sizing  # noqa: E402

OUT = ROOT / "cad" / "m3_wash_spec.json"

CAPSULES = 10000                 # sizing.py "mvp" preset
MESH_OPENING_UM = 25             # bought mesh; 0.36 x 70 um capsule, inside the sheet's 21-28 um trap gap
CHAMBER_HEIGHT_UM = 150          # >= 2 x 70 um swollen capsule (sheet: >= ~150 um)
CHANNEL_FACTOR = 2.0             # channels at 2 x capsule diameter
PORT_WIDTH_UM = 500              # tubing/pipette ports
MARGIN_MM = 6.5                  # plate around the trap (room for ports and channels)
BASE_MM, LID_MM = 1.0, 1.0       # PMMA


def build() -> dict:
    s = sizing.compute(sizing.PRESETS["mvp"] | {"capsule_count": CAPSULES})
    d = s["inputs"]["capsule_diameter_um"]
    side = round(math.sqrt(s["monolayer_area_cm2"] * 100), 3)        # mm, square monolayer
    h = CHAMBER_HEIGHT_UM / 1000
    fx, fy = round(side + 2 * MARGIN_MM, 3), round(side + 2 * 2.5, 3)
    cx, cy = fx / 2, fy / 2
    top = BASE_MM + h + LID_MM
    w = round(CHANNEL_FACTOR * d / 1000, 4)
    port = lambda pid, typ, x, y, z, role, passable: {  # noqa: E731
        "id": pid, "type": typ, "position": [round(x, 3), round(y, 3), round(z, 3)],
        "role": role, "capsule_passable": passable, "width_um": PORT_WIDTH_UM}
    return {
        "id": "m3_wash_v1",
        "name": "Module 3: capsule wash (real scale, draft)",
        "description": ("One capsule trap for 10,000 capsules on a bought 25 um mesh: load from above, wash down to "
                        "waste below the mesh, back-flush from below to resuspend, release. GENERATED by "
                        "cad/generators/m3_wash.py from operator/sizing.py; edit the script, not this file."),
        "placeholder": True,
        "module": {"id": "m3", "name": "Capsule wash", "status": "draft", "printed": True},
        "generator": {"script": "cad/generators/m3_wash.py",
                      "params": {"capsule_count": CAPSULES, "mesh_opening_um": MESH_OPENING_UM,
                                 "chamber_height_um": CHAMBER_HEIGHT_UM, "channel_width_factor": CHANNEL_FACTOR}},
        "units": "mm",
        "footprint": {"x": fx, "y": fy},
        "layers": [
            {"id": "m3_base", "material": "pmma", "thickness_mm": BASE_MM},
            {"id": "m3_fluidic", "material": "pmma", "thickness_mm": h},
            {"id": "m3_lid", "material": "pmma", "thickness_mm": LID_MM},
        ],
        "capsule": {"diameter_um": d, "swell_factor": s["inputs"]["swell_factor"], "count": CAPSULES},
        "trap": {"gap_um": MESH_OPENING_UM},
        "chambers": [{
            "id": "m3_trap_1", "type": "exchange",
            "center": [cx, cy, round(BASE_MM + h / 2, 4)], "size": [side, side, h],
            "height_um": CHAMBER_HEIGHT_UM,
            "volume_ul": round(side * side * h, 3),
            "retention": {"type": "mesh", "opening_um": MESH_OPENING_UM, "source": "bought"},
        }],
        "channels": [
            {"id": "m3_ch_load", "from": "m3_inlet_1", "to": "m3_trap_1", "width_mm": w, "depth_mm": h},
            {"id": "m3_ch_waste", "from": "m3_trap_1", "to": "m3_waste_1", "width_mm": w, "depth_mm": h},
            {"id": "m3_ch_backflush", "from": "m3_backflush_1", "to": "m3_trap_1", "width_mm": w, "depth_mm": h},
            {"id": "m3_ch_release", "from": "m3_trap_1", "to": "m3_release_1", "width_mm": w, "depth_mm": h},
        ],
        "ports": [
            port("m3_inlet_1", "inlet", cx, cy, top, "load", True),                        # above the trap
            port("m3_backflush_1", "inlet", MARGIN_MM / 2, cy, 0, "backflush", False),     # below the mesh
            port("m3_waste_1", "outlet", fx - MARGIN_MM / 2, cy, 0, "waste", False),       # below the mesh
            port("m3_release_1", "outlet", cx, fy - 1.25, top, "release", True),           # past the trap's far edge
        ],
    }


def main() -> int:
    spec = build()
    errors = schema_io.schema_errors("chip_spec", spec)
    if errors:
        for e in errors:
            print(f"ERROR {schema_io.path_str(e)}: {schema_io.describe(e)}", file=sys.stderr)
        return 1
    schema_io.write_json(OUT, spec)
    c = spec["chambers"][0]
    print(f"wrote cad/{OUT.name}: trap {c['size'][0]} x {c['size'][1]} mm x {c['height_um']} um "
          f"({c['volume_ul']} uL) for {spec['capsule']['count']:,} capsules; footprint "
          f"{spec['footprint']['x']} x {spec['footprint']['y']} mm")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
