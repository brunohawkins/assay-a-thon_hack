def _footprint(spec: dict | None) -> str:
    if not spec:
        return "-"
    f = spec.get("footprint") or {}
    return f"{f.get('x', 0):g} x {f.get('y', 0):g}"


def _layers(spec: dict | None) -> str:
    if not spec:
        return "-"
    ls = spec.get("layers") or []
    mats = sorted({l.get("material", "?") for l in ls})
    return f"{len(ls)} ({', '.join(mats)})"


def _ports(spec: dict | None) -> str:
    if not spec:
        return "-"
    ps = spec.get("ports") or []
    n_in = sum(1 for p in ps if p.get("type") == "inlet")
    n_out = sum(1 for p in ps if p.get("type") == "outlet")
    n_c = sum(1 for p in ps if p.get("type") == "control")
    return f"{len(ps)} ({n_in} in, {n_out} out" + (f", {n_c} control" if n_c else "") + ")"


def _findings(entry) -> list[dict]:
    return list((entry or {}).get("violations") or []) if isinstance(entry, dict) else []


def _count(items: list[dict]) -> str:
    e = sum(1 for v in items if v.get("severity") == "error")
    w = sum(1 for v in items if v.get("severity") == "warning")
    i = len(items) - e - w
    bits = [f"{e} error{'s' if e != 1 else ''}" if e else "", f"{w} warning{'s' if w != 1 else ''}" if w else "",
            f"{i} note{'s' if i != 1 else ''}" if i else ""]
    return ", ".join(b for b in bits if b) or "none"


def build_blocks(source, ir, plan, chips, programs, checks, constraints, out_dir: Path, agent_desc, rows,
                 pipeline_errors, files_index) -> list[tuple]:
    from autochip import constraints as C
    B: list[tuple] = []
    src = source or {}
    title = ir.get("name") or ir.get("id")
    B.append(("h1", f"autochip report: {title}"))
    # at the top: which agent ran, and any extract FALLBACK marker (the rules extractor stood in for the agent)
    fallbacks = [str(a).strip() for a in (ir.get("assumptions") or []) if str(a).strip().upper().startswith("FALLBACK:")]
    banner = [("Agent", agent_desc or "not recorded")]
    banner += [("FALLBACK", re.sub(r"^\s*FALLBACK:\s*", "", f, flags=re.I)) for f in fallbacks]
    B.append(("banner", banner))
    n_err =sum(1 for cs in checks.values() for c in cs if c.get("severity") == "error")
    n_warn = sum(1 for cs in checks.values() for c in cs if c.get("severity") == "warning")
    n_on = sum(1 for r in rows if r["kind"] == "on_chip")
    n_off = sum(1 for r in rows if r["kind"] == "off_chip")
    n_miss = sum(1 for r in rows if r["kind"] in ("missing", "unassigned"))
    layout_err = sum(1 for c in plan.get("chips", []) for v in _findings((chips or {}).get(c["id"])) if v.get("severity") == "error")
    B.append(("stats", [("Protocol steps", len(ir.get("steps", []))), ("Chips", len(plan.get("chips", []))),
                        ("Modules", sum(len(c.get("modules", [])) for c in plan.get("chips", []))),
                        ("On chip / bench / missing", f"{n_on} / {n_off} / {n_miss}"),
                        ("Layout errors", layout_err), ("Flow-check errors / warnings", f"{n_err} / {n_warn}")]))
    B.append(("p", f"{len(plan.get('chips', []))} chip(s) do {n_on} of the {len(ir.get('steps', []))} protocol steps; "
                   f"{n_off} stay at the bench and {n_miss} need a part the library doesn't have. "
                   "Everything here is generated: flows, volumes and times the source did not give are placeholders."))
    # open problems: every error anywhere (flow checks, the operator's safety blocks, layout), missing parts, gaps
    problems = []
    for c in plan.get("chips", []):
        for x in checks.get(c["id"], []):
            if x.get("severity") == "error":
                problems.append(f"**{c['id']}**: {x['message']}")
        for v in _findings((chips or {}).get(c["id"])):
            if v.get("severity") == "error":
                problems.append(f"**{c['id']}** (layout): {v.get('message', '')}")
    for r in rows:
        if r["kind"] == "missing":
            problems.append(f"step {r['n']}: missing part ({r.get('need') or '?'})"
                            + (f"; workaround: {r['workaround']}" if r.get("workaround") else ""))
        elif r["kind"] == "unassigned":
            problems.append(f"step {r['n']}: not assigned to a chip, the bench or a missing part")
    problems += [f"pipeline.json does not match its schema: {e}" for e in pipeline_errors]
    B.append(("h2", "Open problems"))
    B.append(("ul", problems) if problems else ("p", "None found: no errors, missing parts or unassigned steps."))
    B.append(("svg_overview",))
    # what went in
    B.append(("h2", "What went in"))
    irsrc = ir.get("source") or {}
    B.append(("table", ["", ""], [
        ["Source", f"{src.get('kind') or irsrc.get('kind') or '-'}: {src.get('title') or irsrc.get('title') or '-'}"],
        ["File", src.get("file") or irsrc.get("file") or "-"],
        ["Citation", irsrc.get("citation") or "-"],
        ["User goal", src.get("prompt") or "-"],
        ["Protocol goal (as extracted)", ir.get("goal") or "-"],
        ["Agent", agent_desc or "-"],
        ["Constraints", f"{(constraints or {}).get('id', '-')}: {(constraints or {}).get('name', '')}"]]))
    B.append(("h2", "Constraints"))
    try:
        B.append(("ul", [re.sub(r"^\s*-\s*", "", ln) for ln in C.summary(constraints).splitlines()[1:]]))
    except Exception:
        B.append(("p", "No constraints summary available."))
    # chips
    B.append(("h2", "Chips"))
    if plan.get("rationale"):
        B.append(("p", f"Why the protocol is split this way: {plan['rationale']}"))
    trows = []
    for c in plan.get("chips", []):
        spec = _spec(chips, c["id"])
        mods = ", ".join(f"{m['id']} ({m.get('part', '')})" for m in c.get("modules", []))
        trows.append([f"**{c['id']}** {c.get('name', '')}", c.get("purpose", ""), ", ".join(map(str, c.get("steps", []))),
                      mods, _ports(spec), _footprint(spec), _layers(spec), _count(_findings((chips or {}).get(c["id"])))])
    B.append(("table", ["Chip", "Purpose", "Steps", "Modules (part)", "Ports", "Footprint (mm)", "Layers", "Constraint findings"],
              trows))
    for c in plan.get("chips", []):
        fs = _findings((chips or {}).get(c["id"]))
        if fs:
            B.append(("h3", f"{c['id']}: constraint findings"))
            B.append(("ul", [f"**{v.get('severity')}** {('[' + v['rule'] + '] ') if v.get('rule') else ''}{v.get('message', '')}"
                             for v in fs]))
        if c.get("why_separate"):
            B.append(("p", f"*{c['id']} is its own chip because:* {c['why_separate']}"))
    # coverage
    B.append(("h2", "Step coverage"))
    prog_n = {}
    for cid, prog in programs.items():
        for ph in prog.get("steps", []):
            prog_n.setdefault(ph["ir_step"], []).append(f"{cid} #{ph['n']} {ph['title']}")
    cov_rows = []
    for r in rows:
        if r["kind"] == "handoff":
            continue
        where = {"on_chip": f"{r.get('chip')}.{r.get('module')}", "off_chip": "off chip (bench)",
                 "missing": f"missing: {r.get('need') or ''}", "unassigned": "NOT ASSIGNED"}[r["kind"]]
        cov_rows.append([str(r["n"]), r.get("action") or "", r.get("text") or "", where, "; ".join(prog_n.get(r["n"], []))])
    B.append(("table", ["Step", "Action", "What", "Where", "Run steps"], cov_rows))
    # off chip, missing, handoffs
    B.append(("h2", "Off-chip steps"))
    if plan.get("off_chip"):
        B.append(("table", ["Steps", "Why off chip", "Equipment"],
                  [[", ".join(map(str, g.get("steps", []))), g.get("why", ""), ", ".join(g.get("equipment", []) or [])]
                   for g in plan["off_chip"]]))
    else:
        B.append(("p", "None: every step runs on a chip or is flagged as missing."))
    B.append(("h2", "Missing parts"))
    if plan.get("missing_parts"):
        B.append(("table", ["Steps", "Need", "Why", "Workaround"],
                  [[", ".join(map(str, g.get("steps", []))), g.get("need", ""), g.get("why", ""), g.get("workaround") or "-"]
                   for g in plan["missing_parts"]]))
    else:
        B.append(("p", "None."))
    B.append(("h2", "Hand-offs"))
    hr = [r for r in rows if r["kind"] == "handoff" and r.get("phase") != "in"]
    if hr:
        B.append(("table", ["From", "To", "Carries", "How", "Via bench steps"],
                  [[f"{r['from_chip']} `{r['from_port']}`", f"{r['to_chip']} `{r['to_port']}`", r.get("carries") or "",
                    (r.get("method") or "").replace("_", " "), ", ".join(map(str, r.get("via_steps") or [])) or "-"] for r in hr]))
    else:
        B.append(("p", "None (one chip, or the plan lists no hand-offs)."))
    # assumptions
    B.append(("h2", "Assumptions"))
    assum = [f"(extract) {a}" for a in ir.get("assumptions", []) or []]
    assum += [f"(extract) step {s['n']} was inferred, not stated: {s.get('text', '')}" for s in ir.get("steps", []) if s.get("assumed")]
    assum += [
        f"(run plan) Exchanges push {RP.FLUSH_VOLUMES} chamber volumes per wash; bench volumes don't carry over to the chip.",
        "(run plan) Default flows where the protocol gives none: " + ", ".join(f"{k} {v:g}" for k, v in RP.DEFAULT_FLOW.items())
        + f", anything else {RP.DEFAULT_FLOW_OTHER:g} uL/min; lowered automatically when the chamber shear limit "
          f"({', '.join(f'{k} {v:g}' for k, v in RP.CHAMBER_SHEAR_LIMIT.items())} dyn/cm2) would be passed.",
        "(run plan) Encapsulation co-flow when the chip spec has none: core / shell / oil "
        + " / ".join(f"{v:g}" for v in RP.ENCAP_FLOWS_UL_H.values()) + " uL/h.",
        "(run plan) No on-chip valves: each step's flow is set by which syringe pushes, which outlet is open and which ports are capped.",
        "(run plan) Pressures are on-chip only (operator/network.py); tubing adds to what the pump sees."]
    B.append(("ul", assum))
    # flow checks
    B.append(("h2", "Flow-check results"))
    B.append(("p", "Every step's port states were solved with operator/network.py on the chip spec: does the flow go through "
                   "the target module, does anything flow back into modules holding other material, pressure against the "
                   "constraints, shear in cell- and capsule-holding modules, pump range and number of pump lines."))
    for c in plan.get("chips", []):
        prog = programs.get(c["id"])
        B.append(("h3", f"{c['id']}: {c.get('name', '')}"))
        if not prog:
            B.append(("p", "No run program (no chip spec)."))
        else:
            fr = []
            for ph in prog.get("steps", []):
                fc = ph.get("flow_check") or {}
                if fc.get("solved"):
                    res = "OK" if fc.get("ok") else "ERROR"
                    msgs = [i["message"] for i in fc.get("issues", []) if i["severity"] != "info"]
                    fr.append([str(ph["n"]), str(ph["ir_step"]), ph["module"], ph["title"], RP.port_summary(ph),
                               f"{fc.get('through_target_ul_min', 0):g}", f"{fc.get('max_pressure_kpa', 0):.3g}",
                               f"{fc.get('target_shear_dyn_cm2', 0):.3g}", res + (": " + "; ".join(msgs) if msgs else "")])
                else:
                    fr.append([str(ph["n"]), str(ph["ir_step"]), ph["module"], ph["title"], RP.port_summary(ph), "", "", "",
                               fc.get("note") or ("ERROR: " + "; ".join(i["message"] for i in fc.get("issues", [])))])
            B.append(("table", ["#", "IR step", "Module", "What", "Port states", "Through target (uL/min)", "Max kPa",
                                "Shear (dyn/cm2)", "Result"], fr))
        cs = [x for x in checks.get(c["id"], []) if x.get("severity") in ("error", "warning")]
        if cs:
            B.append(("ul", [f"**{x['severity']}** {x['message']}" for x in cs]))
        tw = (prog or {}).get("twin_run")
        if tw:
            B.append(("p", (f"Operator planner: accepted, {tw['events']} events in `runs/{c['id']}.twin_run.json`."
                            if tw.get("ok") else f"Operator planner: not accepted ({tw.get('error')}).")))
    if pipeline_errors:
        B.append(("h3", "pipeline.json"))
        B.append(("ul", [f"**error** does not match pipeline.schema.json: {e}" for e in pipeline_errors]))
    B.append(("pipeline_sheet",))
    B.append(("chip_drawings",))
    B.append(("h2", "Files"))
    B.append(("ul", [f"`{f}`: {d}" for f, d in files_index]))
    return B


