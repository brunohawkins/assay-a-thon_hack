def _programs(runs: dict, out_dir: Path) -> dict[str, dict]:
    """Each chip's run program: from the runplan result, else from runs/<chip>.run.json (resumed runs)."""
    out = {}
    for cid, r in (runs or {}).items():
        prog = (r or {}).get("program")
        if not prog:
            p = out_dir / "runs" / f"{cid}.run.json"
            if p.exists():
                try:
                    prog = json.loads(p.read_text())
                except json.JSONDecodeError:
                    prog = None
        if prog:
            out[cid] = prog
    return out


def _checks(runs: dict, programs: dict) -> dict[str, list[dict]]:
    out = {}
    for cid in set(runs or {}) | set(programs):
        cs = ((runs or {}).get(cid) or {}).get("checks") or (programs.get(cid) or {}).get("checks") or []
        out[cid] = cs
    return out


def _spec(chips: dict, cid: str) -> dict | None:
    e = (chips or {}).get(cid)
    return e.get("spec") if isinstance(e, dict) else None


def _path_for_pipeline(p: Path, out_dir: Path) -> str:
    """Repo-relative when the output folder is inside the repo (what the twin expects), else relative to out_dir."""
    try:
        return p.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return p.resolve().relative_to(out_dir.resolve()).as_posix()


def _carries(text: str | None, fallback: str | None = None) -> str:
    t = f"{text or ''} {fallback or ''}".lower()
    if "capsule" in t or "droplet" in t:
        return "capsules"
    if any(w in t for w in ("library", "dna", "cdna", "nucleic", "lysate")):
        return "library"
    return "cells"


def build_pipeline(ir: dict, plan: dict, chips: dict, programs: dict, constraints: dict, out_dir: Path) -> dict:
    snake = RP.snake
    connector = (constraints or {}).get("ports", {}).get("connector")
    conn = snake(connector) if connector else "TBC"
    method = ((constraints or {}).get("fabrication") or {}).get("method") or "not stated"
    placement = ((constraints or {}).get("ports") or {}).get("placement")
    modules, mod_id = [], {}
    for c in plan.get("chips", []):
        mid = snake(c["id"], "chip")
        mod_id[c["id"]] = mid
        spec_p = out_dir / "chips" / f"{c['id']}.json"
        proto_p = out_dir / "runs" / f"{c['id']}.protocol.json"
        m = {"module": mid, "name": c.get("name") or c["id"]}
        if _spec(chips, c["id"]) or spec_p.exists():
            m.update({"status": "draft", "status_note": "generated by autochip; placeholder values",
                      "chip": _path_for_pipeline(spec_p, out_dir)})
        else:
            m.update({"status": "missing", "status_note": "no chip spec was produced"})
        if proto_p.exists():
            m["protocol"] = _path_for_pipeline(proto_p, out_dir)
        m["build"] = {"method": method.replace("_", " "), "connector": conn,
                      "ports": f"{connector or 'TBC'}" + (f", on the {placement}" if placement else "")}
        m["built_for_demo"] = False
        m["note"] = c.get("purpose") or ""
        modules.append(m)
    handoffs, used = [], set()
    rows = RP.pipeline_sequence(plan, ir, programs, {c["id"]: _spec(chips, c["id"]) or {} for c in plan.get("chips", [])})
    hrows = {(r["from_chip"], r["to_chip"]): r for r in rows if r["kind"] == "handoff"}
    for h in plan.get("handoffs", []):
        a, b = h["from_chip"], h["to_chip"]
        if a not in mod_id or b not in mod_id:
            continue
        hid = snake(f"{a}_to_{b}")
        while hid in used:
            hid += "_2"
        used.add(hid)
        r = hrows.get((a, b), {})
        progs = (programs.get(a) or {}).get("steps", [])
        b_first = min((int(x) for c in plan["chips"] if c["id"] == b for x in c.get("steps", []) or []), default=None)
        before = [p["n"] for p in progs if b_first is None or p["ir_step"] < b_first]
        entry = {"id": hid,
                 "from": {"module": mod_id[a], "port": snake(r.get("from_port") or "outlet_1")},
                 "to": {"module": mod_id[b], "port": snake(r.get("to_port") or "inlet_1")},
                 "carries": _carries(h.get("carries")),
                 "connector": {"from": conn, "to": conn, "status": "unknown" if conn == "TBC" else "match"},
                 "note": (f"{h.get('carries')} by {h.get('method', '').replace('_', ' ')}"
                          + (f", through bench step(s) {', '.join(map(str, h['via_steps']))}" if h.get("via_steps") else ""))}
        if conn == "TBC":
            entry["connector"]["warning"] = "Port style not decided in the constraints: check the tubing fits both chips."
        if before or progs:
            entry["after_step"] = max(before or [p["n"] for p in progs])
        handoffs.append(entry)
    last = max((int(n) for c in plan.get("chips", []) for n in (c.get("steps") or [])), default=0)
    tail = [r for r in rows if r["kind"] in ("off_chip", "missing") and r["n"] > last]
    pipe = {"kind": "pipeline", "id": snake(plan.get("id") or "autochip_pipeline", "pipeline"),
            "name": plan.get("name") or ir.get("name") or plan.get("id"), "placeholder": True,
            "description": (f"Generated by autochip from '{ir.get('name') or ir.get('id')}'. "
                            + (plan.get("rationale") or "")).strip(),
            "modules": modules, "handoffs": handoffs}
    if tail:
        pipe["roadmap"] = [{"id": snake(f"step_{r['n']}_{r['kind']}"),
                            "name": f"{'Bench' if r['kind'] == 'off_chip' else 'Missing part'}: step {r['n']}",
                            "note": r.get("text") or ""} for r in tail]
    return pipe


def _validate(name: str, obj: dict) -> list[str]:
    errs = RP._validator(name).iter_errors(obj)
    return [f"{'/'.join(map(str, e.absolute_path)) or '(top)'}: {e.message[:200]}" for e in errs]


# --- overview drawing ----------------------------------------------------------------------------

NODE_W, GAP_X, GAP_Y, MARGIN, LINE_H, HEAD_H = 250, 64, 70, 24, 16, 40
COLORS = {"chip": ("#f6f7f9", "#4b5563"), "bench": ("#ffffff", "#9ca3af"), "missing": ("#fff8eb", "#b7791f"),
          "text": "#111827", "muted": "#6b7280", "arrow": "#6b7280", "head": "#e8eaee"}


def _wrap(text: str, width: int = 36) -> list[str]:
    words, lines, cur = str(text).split(), [], ""
    for w in words:
        if len(cur) + len(w) + 1 > width and cur:
            lines.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}".strip()
    if cur:
        lines.append(cur)
    return lines or [""]


def overview_nodes(plan: dict, rows: list[dict]) -> list[dict]:
    """Chips, bench groups and missing parts in protocol order, each with its text lines."""
    chips = {c["id"]: c for c in plan.get("chips", [])}
    nodes: list[dict] = []
    seen_chip: dict[str, dict] = {}
    handoff_label: dict[str, str] = {}
    for r in rows:
        if r["kind"] == "handoff" and r.get("phase") != "in":
            handoff_label[r["from_chip"]] = f"{r.get('carries') or ''} ({(r.get('method') or '').replace('_', ' ')})"
    # a missing step between two steps of the same chip is drawn inside that chip's box
    span = {}
    for r in rows:
        if r["kind"] == "on_chip":
            lo, hi = span.get(r["chip"], (r["n"], r["n"]))
            span[r["chip"]] = (min(lo, r["n"]), max(hi, r["n"]))
    inside = {r["n"]: cid for r in rows if r["kind"] in ("missing", "off_chip")
              for cid, (lo, hi) in span.items() if lo < r["n"] < hi}
    for r in rows:
        k = r["kind"]
        if k in ("missing", "off_chip") and r["n"] in inside:
            continue
        if k == "on_chip":
            if r["chip"] in seen_chip:
                continue
            c = chips.get(r["chip"], {"id": r["chip"], "modules": []})
            lines = _wrap(c.get("name") or "", 38) if c.get("name") else []
            for m in c.get("modules", []):
                st = ", ".join(map(str, m.get("steps", [])))
                lines += _wrap(f"{m['id']}" + (f": steps {st}" if st else ""), 38)
                lines.append(f"   {m.get('part', '')}"[:40])
            for r2 in rows:
                if r2["kind"] in ("missing", "off_chip") and inside.get(r2["n"]) == c["id"]:
                    what = (f"missing (step {r2['n']}): {r2.get('need') or r2.get('text')}" if r2["kind"] == "missing"
                            else f"bench (step {r2['n']}): {r2.get('text')}")
                    lines += _wrap(what, 38)
            node = {"kind": "chip", "id": c["id"], "title": c["id"], "lines": lines,
                    "label_out": handoff_label.get(c["id"])}
            seen_chip[r["chip"]] = node
            nodes.append(node)
        elif k in ("off_chip", "missing", "unassigned"):
            kind = "bench" if k == "off_chip" else "missing"
            text = f"{r['n']}. {r.get('text') or ''}"
            if k == "missing" and r.get("need"):
                text += f" [need: {r['need']}]"
            if nodes and nodes[-1]["kind"] == kind and not nodes[-1].get("closed"):
                nodes[-1]["lines"] += _wrap(text, 38)
            else:
                nodes.append({"kind": kind, "id": f"{kind}_{r['n']}",
                              "title": "Bench (off chip)" if kind == "bench" else "Missing part", "lines": _wrap(text, 38)})
        if k != "on_chip" and nodes and nodes[-1]["kind"] == "chip":
            nodes[-1]["closed"] = True
        if k == "on_chip":
            for n in nodes:
                if n["kind"] != "chip":
                    n["closed"] = True
    return nodes


def _line_color(n: dict, ln: str) -> str:
    if n["kind"] != "chip":
        return COLORS["muted"]
    if ln.startswith("missing"):
        return COLORS["missing"][1]
    if ln.startswith("bench"):
        return COLORS["muted"]
    return COLORS["muted"] if ln.startswith("   ") else COLORS["text"]


def overview_layout(nodes: list[dict], per_row: int = 4) -> tuple[list[dict], float, float]:
    rows = [nodes[i:i + per_row] for i in range(0, len(nodes), per_row)] or [[]]
    y = MARGIN + 30
    for row in rows:
        h = max((HEAD_H + LINE_H * max(len(n["lines"]), 1) + 14 for n in row), default=80)
        for i, n in enumerate(row):
            n["x"] = MARGIN + i * (NODE_W + GAP_X)
            n["y"] = y
            n["w"] = NODE_W
            n["h"] = HEAD_H + LINE_H * max(len(n["lines"]), 1) + 14
            n["row_h"] = h
        y += h + GAP_Y
    width = MARGIN * 2 + min(len(nodes), per_row) * NODE_W + (min(len(nodes), per_row) - 1) * GAP_X
    return nodes, max(width, 360), y - GAP_Y + MARGIN


def overview_svg(title: str, nodes: list[dict]) -> str:
    nodes, W, H = overview_layout(nodes)
    e = html.escape
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W:.0f} {H:.0f}" width="{W:.0f}" height="{H:.0f}" '
         f'font-family="Helvetica, Arial, sans-serif" role="img" aria-label="{e(title)}">',
         '<defs><marker id="arr" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto">'
         f'<path d="M0,0 L10,5 L0,10 z" fill="{COLORS["arrow"]}"/></marker></defs>',
         f'<rect width="100%" height="100%" fill="#ffffff"/>',
         f'<text x="{MARGIN}" y="{MARGIN + 6}" font-size="15" font-weight="700" fill="{COLORS["text"]}">{e(title)}</text>']
    for a, b in zip(nodes[:-1], nodes[1:]):
        if abs(a["y"] - b["y"]) < 1:
            x1, y1, x2, y2 = a["x"] + a["w"], a["y"] + 22, b["x"], b["y"] + 22
            o.append(f'<path d="M{x1},{y1} L{x2 - 2},{y2}" stroke="{COLORS["arrow"]}" stroke-width="1.6" fill="none" '
                     f'marker-end="url(#arr)"/>')
            lx = (x1 + x2) / 2
        else:
            x1, y1 = a["x"] + a["w"] / 2, a["y"] + a["h"]
            x2, y2 = b["x"] + b["w"] / 2, b["y"]
            ym = a["y"] + a["row_h"] + GAP_Y / 2
            o.append(f'<path d="M{x1},{y1} L{x1},{ym} L{x2},{ym} L{x2},{y2 - 2}" stroke="{COLORS["arrow"]}" '
                     f'stroke-width="1.6" fill="none" marker-end="url(#arr)"/>')
            lx, y1 = (x1 + x2) / 2, ym - 6
        if a.get("label_out"):
            for i, ln in enumerate(_wrap(a["label_out"], 12)[:3]):
                o.append(f'<text x="{lx:.0f}" y="{y1 - 8 - 12 * (len(_wrap(a["label_out"], 12)[:3]) - 1 - i):.0f}" '
                         f'font-size="10" text-anchor="middle" fill="{COLORS["muted"]}">{e(ln)}</text>')
    for n in nodes:
        fill, stroke = COLORS[n["kind"]]
        dash = ' stroke-dasharray="5 4"' if n["kind"] in ("bench", "missing") else ""
        rx = 10 if n["kind"] == "bench" else 6
        o.append(f'<rect x="{n["x"]}" y="{n["y"]}" width="{n["w"]}" height="{n["h"]}" rx="{rx}" fill="{fill}" '
                 f'stroke="{stroke}" stroke-width="1.4"{dash}/>')
        if n["kind"] == "chip":
            o.append(f'<path d="M{n["x"] + 1},{n["y"] + 30} L{n["x"] + n["w"] - 1},{n["y"] + 30}" stroke="{stroke}" '
                     f'stroke-width="0.8"/>')
        o.append(f'<text x="{n["x"] + 10}" y="{n["y"] + 20}" font-size="13" font-weight="700" fill="{COLORS["text"]}">'
                 f'{e(n["title"][:34])}</text>')
        for i, ln in enumerate(n["lines"]):
            o.append(f'<text x="{n["x"] + 10}" y="{n["y"] + HEAD_H + 6 + i * LINE_H}" font-size="11" '
                     f'fill="{_line_color(n, ln)}" xml:space="preserve">{e(ln)}</text>')
    o.append("</svg>")
    return "\n".join(o)


def overview_png(title: str, nodes: list[dict], path: Path) -> bool:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from matplotlib.patches import FancyBboxPatch
    except Exception:
        return False
    nodes, W, H = overview_layout(nodes)
    fig = plt.figure(figsize=(W / 100, H / 100), dpi=150)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, W)
    ax.set_ylim(H, 0)
    ax.axis("off")
    ax.text(MARGIN, MARGIN + 6, title, fontsize=10.5, fontweight="bold", color=COLORS["text"], va="baseline")
    for a, b in zip(nodes[:-1], nodes[1:]):
        if abs(a["y"] - b["y"]) < 1:
            ax.annotate("", xy=(b["x"], b["y"] + 22), xytext=(a["x"] + a["w"], a["y"] + 22),
                        arrowprops=dict(arrowstyle="-|>", color=COLORS["arrow"], lw=1.2))
            if a.get("label_out"):
                ax.text((a["x"] + a["w"] + b["x"]) / 2, a["y"] + 14, "\n".join(_wrap(a["label_out"], 12)[:3]),
                        fontsize=6.5, ha="center", va="bottom", color=COLORS["muted"])
        else:
            ym = a["y"] + a["row_h"] + GAP_Y / 2
            x1, x2 = a["x"] + a["w"] / 2, b["x"] + b["w"] / 2
            ax.plot([x1, x1, x2], [a["y"] + a["h"], ym, ym], color=COLORS["arrow"], lw=1.2)
            ax.annotate("", xy=(x2, b["y"]), xytext=(x2, ym), arrowprops=dict(arrowstyle="-|>", color=COLORS["arrow"], lw=1.2))
    for n in nodes:
        fill, stroke = COLORS[n["kind"]]
        ax.add_patch(FancyBboxPatch((n["x"], n["y"]), n["w"], n["h"], boxstyle="round,pad=0,rounding_size=6",
                                    fc=fill, ec=stroke, lw=1.0, ls="--" if n["kind"] != "chip" else "-"))
        ax.text(n["x"] + 10, n["y"] + 20, n["title"][:34], fontsize=9, fontweight="bold", color=COLORS["text"], va="baseline")
        for i, ln in enumerate(n["lines"]):
            ax.text(n["x"] + 10, n["y"] + HEAD_H + 6 + i * LINE_H, ln, fontsize=7.5, va="baseline", color=_line_color(n, ln))
    fig.savefig(path, facecolor="white")
    plt.close(fig)
    return True


