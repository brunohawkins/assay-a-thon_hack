def _md_cell(s) -> str:
    return str(s if s is not None else "").replace("|", "/").replace("\n", " ")


def render_md(blocks: list[tuple]) -> str:
    L: list[str] = []
    for b in blocks:
        k = b[0]
        if k == "h1":
            L += [f"# {b[1]}", ""]
        elif k == "h2":
            L += [f"## {b[1]}", ""]
        elif k == "h3":
            L += [f"### {b[1]}", ""]
        elif k == "p":
            L += [b[1], ""]
        elif k == "ul":
            L += [f"- {x}" for x in b[1]] + [""]
        elif k == "banner":
            for i, (lbl, v) in enumerate(b[1]):
                L += ([">"] if i else []) + [f"> **{lbl}:** {v}"]
            L += [""]
        elif k == "stats":
            L += [" · ".join(f"**{v}** {lbl.lower()}" for lbl, v in b[1]), ""]
        elif k == "table":
            hdr, rows = b[1], b[2]
            if hdr == ["", ""]:
                L += ["| | |", "|---|---|"] + [f"| **{_md_cell(r[0])}** | {_md_cell(r[1])} |" for r in rows] + [""]
            else:
                L += ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
                L += ["| " + " | ".join(_md_cell(c) for c in r) + " |" for r in rows] + [""]
        elif k == "svg_overview":
            L += ["![Pipeline overview](overview.svg)", ""]
        elif k == "pipeline_sheet":
            L += ["## Lab run sheet", "", "The whole protocol as it runs in the lab, step by step across the chips, is in "
                  "[`runs/pipeline_run_sheet.md`](runs/pipeline_run_sheet.md); each chip's set-up and step table is in "
                  "`runs/<chip>.run_sheet.md`.", ""]
        elif k == "chip_drawings":
            pass
    return RP.units("\n".join(L).rstrip() + "\n")


def _inline(s: str) -> str:
    t = html.escape(RP.units(str(s if s is not None else "")))
    t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", t)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', t)
    return t


