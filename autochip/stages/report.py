def _strip_svg(text: str) -> str:
    text = re.sub(r"<\?xml[^>]*\?>", "", text)
    text = re.sub(r"<!DOCTYPE[^>]*>", "", text)
    return text.strip()


def _seq_html(rows: list[dict]) -> str:
    o = ['<ol class="seq">']
    for r in rows:
        k = r["kind"]
        if k == "handoff":
            o.append(f'<li class="handoff"><span class="tag">hand-off</span>{_inline(r["text"])}</li>')
            continue
        tag = {"on_chip": f"step {r['n']} · {r.get('chip')} · {r.get('module')}", "off_chip": f"step {r['n']} · bench",
               "missing": f"step {r['n']} · missing part", "unassigned": f"step {r['n']} · not assigned"}[k]
        body = _inline(r.get("text") or "")
        extra = []
        if k == "on_chip":
            for p in r.get("phases", []):
                bits = [p["ports"], RP.fmt_dur(p["duration_s"])]
                if p.get("temp_c") is not None:
                    bits.append(f"{p['temp_c']:g} C")
                if p.get("light"):
                    bits.append(f"light {p['light']['wavelength_nm']:g} nm")
                if p.get("magnet"):
                    bits.append("magnet on")
                extra.append(f'<div class="ph">#{p["n"]} <strong>{_inline(p["title"])}</strong>: '
                             f'{_inline("; ".join(b for b in bits if b))}. Watch: {_inline(p["watch"])}</div>')
                extra += [f'<div class="ph err">Fix before the run: {_inline(e)}</div>' for e in p.get("errors", [])]
        elif k == "off_chip":
            if r.get("equipment"):
                extra.append(f'<div class="ph">Equipment: {_inline(", ".join(r["equipment"]))}</div>')
            if r.get("why"):
                extra.append(f'<div class="ph">Off chip because: {_inline(r["why"])}</div>')
        elif k == "missing":
            extra.append(f'<div class="ph">Need: {_inline(r.get("need") or "-")}'
                         + (f' · workaround: {_inline(r["workaround"])}' if r.get("workaround") else "") + "</div>")
        o.append(f'<li class="{k}"><span class="tag">{html.escape(tag)}</span>{body}{"".join(extra)}</li>')
    o.append("</ol>")
    return "\n".join(o)


def render_html(blocks: list[tuple], title: str, overview: str, rows: list[dict], programs: dict, plan: dict,
                out_dir: Path) -> str:
    o = [f"<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" "
         f"content=\"width=device-width, initial-scale=1\"><title>{html.escape(title)}</title><style>{CSS}</style></head>"
         f"<body><main>"]
    for b in blocks:
        k = b[0]
        if k in ("h1", "h2", "h3"):
            o.append(f"<{k}>{_inline(b[1])}</{k}>")
        elif k == "p":
            o.append(f"<p>{_inline(b[1])}</p>")
        elif k == "ul":
            items = []
            for x in b[1]:
                x = _inline(x).replace("<strong>error</strong>", '<span class="sev-error">error</span>') \
                              .replace("<strong>warning</strong>", '<span class="sev-warning">warning</span>')
                items.append(f"<li>{x}</li>")
            o.append("<ul>" + "".join(items) + "</ul>")
        elif k == "banner":
            cls = {"FALLBACK": ' class="fallback"'}
            o.append('<div class="banner">' + "".join(
                f'<div{cls.get(lbl, "")}><strong>{html.escape(lbl)}:</strong> {_inline(v)}</div>'
                for lbl, v in b[1]) + "</div>")
        elif k == "stats":
            o.append('<div class="stats">' + "".join(f'<div class="stat"><b>{html.escape(str(v))}</b><span>'
                                                      f'{html.escape(lbl)}</span></div>' for lbl, v in b[1]) + "</div>")
        elif k == "table":
            hdr, rows_ = b[1], b[2]
            if hdr == ["", ""]:
                o.append('<div class="scroll"><table class="kv">' + "".join(
                    f"<tr><td>{_inline(r[0])}</td><td>{_inline(r[1])}</td></tr>" for r in rows_) + "</table></div>")
            else:
                o.append('<div class="scroll"><table><thead><tr>' + "".join(f"<th>{_inline(h)}</th>" for h in hdr)
                         + "</tr></thead><tbody>" + "".join("<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in r) + "</tr>"
                                                            for r in rows_) + "</tbody></table></div>")
        elif k == "svg_overview":
            o.append(f'<div class="figure">{_strip_svg(overview)}</div>')
        elif k == "pipeline_sheet":
            o.append("<h2>Lab run sheet</h2>")
            o.append("<p>The whole protocol as it runs in the lab, in protocol order across chips, bench steps and hand-offs. "
                     "FEED = the pump pushes into the port, VENT = open to a tube, every port not named is capped. "
                     "The same sheet is in <code>runs/pipeline_run_sheet.md</code>.</p>")
            o.append(_seq_html(rows))
            for c in plan.get("chips", []):
                prog = programs.get(c["id"])
                if not prog:
                    continue
                syr = "".join(f"<tr><td><code>{html.escape(r['port'])}</code></td><td>{html.escape(str(r['reagent']))}</td>"
                              f"<td>{r['load_ul']:g}</td><td>{', '.join(map(str, r['steps']))}</td></tr>" for r in prog["syringes"])
                eq = "".join(f"<li>{html.escape(e)}</li>" for e in prog.get("equipment", []))
                o.append(f"<details><summary>{html.escape(c['id'])} set-up: syringes and equipment</summary>"
                         f'<div class="scroll"><table><thead><tr><th>Port</th><th>Syringe</th><th>Load (uL)</th>'
                         f"<th>Run steps</th></tr></thead><tbody>{syr}</tbody></table></div><ul>{eq}</ul></details>")
        elif k == "chip_drawings":
            figs = []
            for c in plan.get("chips", []):
                p = out_dir / "cad" / c["id"] / f"{c['id']}.svg"
                if p.exists():
                    try:
                        figs.append(f"<h3>{html.escape(c['id'])}: {html.escape(c.get('name', ''))}</h3>"
                                    f'<div class="figure">{_strip_svg(p.read_text())}</div>')
                    except OSError:
                        pass
            if figs:
                o.append("<h2>Chip drawings</h2><p>Top views to scale from the layout stage (<code>cad/&lt;chip&gt;/</code>).</p>")
                o += figs
    o.append("<footer>Generated by autochip. Placeholder values throughout; check before a wet-lab run.</footer>")
    o.append("</main></body></html>")
    return "\n".join(o)


