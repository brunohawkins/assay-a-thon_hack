"""Stage 6 (OWNER: agent D). pipeline.json (contracts/schemas/pipeline.schema.json), report.md, overview.svg/.png, report.html.

run(source, ir, plan, chips, runs, constraints, out_dir, agent_desc) -> {"report", "pipeline", "overview", "html", ("png")}
  report.md     what went in, agent, constraints, chip-by-chip table, step coverage, off-chip steps, missing parts,
                hand-offs, assumptions, flow-check results, file index
  pipeline.json the chips as pipeline modules (chip spec + run protocol paths) and the hand-offs between them
  overview.svg  chips as boxes in protocol order with their modules, bench steps and missing parts between them
                (+ overview.png when matplotlib is installed)
  report.html   one self-contained page: the report, the overview, the lab run sheet and every chip's CAD top view
The markdown and the HTML are rendered from the same list of blocks, so they always say the same thing.
"""
