def run(source, ir, plan, chips, runs, constraints, out_dir, agent_desc):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    programs = _programs(runs, out_dir)
    checks = _checks(runs, programs)
    specs = {c["id"]: _spec(chips, c["id"]) or {} for c in plan.get("chips", [])}
    rows = RP.pipeline_sequence(plan, ir, programs, specs)

    pipe = build_pipeline(ir, plan, chips, programs, constraints, out_dir)
    pipe_errors = _validate("pipeline", pipe)
    p_pipe = out_dir / "pipeline.json"
    p_pipe.write_text(json.dumps(pipe, indent=2) + "\n")

    title = ir.get("name") or ir.get("id") or "autochip"
    nodes = overview_nodes(plan, rows)
    svg = overview_svg(f"{title}: chip pipeline", nodes)
    p_svg = out_dir / "overview.svg"
    p_svg.write_text(svg + "\n")
    p_png = out_dir / "overview.png"
    has_png = overview_png(f"{title}: chip pipeline", overview_nodes(plan, rows), p_png)

    p_md = out_dir / "report.md"
    p_html = out_dir / "report.html"
    for p in (p_md, p_html):   # so the file index lists them
        if not p.exists():
            p.write_text("")
    blocks = build_blocks(source, ir, plan, chips, programs, checks, constraints, out_dir, agent_desc, rows,
                          pipe_errors, files_index(out_dir))
    p_md.write_text(render_md(blocks))
    p_html.write_text(render_html(blocks, f"autochip: {title}", svg, rows, programs, plan, out_dir))
    out = {"report": str(p_md), "pipeline": str(p_pipe), "overview": str(p_svg), "html": str(p_html)}
    if has_png:
        out["png"] = str(p_png)
    if pipe_errors:
        out["pipeline_errors"] = pipe_errors
    return out
