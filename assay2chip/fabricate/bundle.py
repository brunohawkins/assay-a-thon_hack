"""One chip spec in, one print bundle out, under cad/exports/<chip_id>/print/.

    from assay2chip.fabricate import bundle
    result = bundle.write(spec)          # or bundle.write(spec, out_dir=...)

The bundle:

    <id>_body.stl               the printable chip body, validated watertight
    <id>_mould.stl              the POSITIVE embossing mould, validated watertight
    <id>.dxf                    closed LWPOLYLINEs, HEADER $INSUNITS = 4 (mm)
    <id>_fusion_rebuild.py      Fusion 360 script, rebuilds both as solids
    render_iso.svg              isometric, flat-shaded, with a scale bar
    render_top.svg              plan view, 1:1, chambers and ports labelled
    manifest.json               units, footprint, depth, material, features, checks,
                                hashes, DEMO vs TARGET scale
    README.md                   what each file is for, for whoever opens the folder

WHY `print/` AND NOT `cad/exports/<chip_id>/` ITSELF. That folder belongs to
cad/make_train_cad.py: it keeps a hidden `.chip_id` owner marker there, names its parts by
bare id, and scans the folder (not its subfolders) for stale STLs. Writing a
`<chip_id>.dxf` next to its own would overwrite it. A subfolder leaves every one of those
invariants intact, and S11 touches nothing it did not write.

NOTHING UNPRINTABLE IS WRITTEN. The STLs are validated BEFORE they reach the disk
(`mesh.write_validated`), so a mesh that is not closed, is inside out or is the wrong size
raises and leaves no file. The fabrication checks are recorded rather than enforced here -
the stage decides what to do about a failure - but a failed check is on the manifest, in
the README and in the stage's return value.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from assay2chip.lib.io import write_json, write_text  # noqa: E402

from . import body as body_mod  # noqa: E402
from . import checks, dxf, fusion, geometry, manifest, mesh  # noqa: E402
from . import mould as mould_mod  # noqa: E402

EXPORTS = ROOT / "cad" / "exports"
PRINT_DIR = "print"


def out_dir_for(chip_id: str, exports_root: Path = None) -> Path:
    """cad/exports/<chip_id>/print/ - one folder per chip, never the flat folder."""
    return (Path(exports_root) if exports_root is not None else EXPORTS) / chip_id / PRINT_DIR


README = """# {chip_id} - print bundle

{warning}

Generated by `assay2chip/stages/s11_fabricate.py`. Everything here is in **millimetres**
at the chip-spec origin: (0, 0) is the lower-left corner of the {fx:g} x {fy:g} mm
footprint and z = 0 is the underside of the chip, so the files line up with each other and
with `chip/{chip_id}.json` without being moved.

| file | what it is |
|---|---|
| `{chip_id}_body.stl` | the chip itself, {body_top:g} mm thick, {n_pockets} pockets {depth_um:g} um deep. Resin-print it directly, or treat it as the shape the embossed sheet takes. Channels are **open**: {seal} |
| `{chip_id}_mould.stl` | the **positive embossing mould** - a {plate:g} mm plate with the same features raised {depth_um:g} um. {mirror} This is the part that goes on the resin printer. |
| `{chip_id}.dxf` | the cut outline. HEADER declares **$INSUNITS = 4 (mm)**, and every entity is a **closed LWPOLYLINE**; cut the `CUT` layer. |
| `{chip_id}_fusion_rebuild.py` | Fusion 360 script. Rebuilds both as editable solids (not mesh imports). |
| `render_iso.svg` | isometric view, flat-shaded, scale bar. Depth is exaggerated {exag:.2g}x and the image says so. |
| `render_top.svg` | plan view, true 1:1, chambers and ports labelled, scale bar. |
| `manifest.json` | units, footprint, depth, material, feature count, every check, file hashes, scale. |

## Both STLs were validated before they were written

{stl_lines}

A mesh that failed any of these would have raised and left no file.

## Fabrication checks

{check_lines}
"""


def write(spec: dict, exports_root: Path = None, pitch: float = None) -> dict:
    """Build and write the whole bundle for one chip spec. Returns the manifest.

    `exports_root` replaces cad/exports/ (tests use a temp dir); the
    <chip_id>/print/ part of the path never changes, because that layout is what keeps
    S11 out of cad/make_train_cad.py's way.
    """
    chip_id = spec["id"]
    out = out_dir_for(chip_id, exports_root)
    out.mkdir(parents=True, exist_ok=True)

    geom = geometry.plan_geometry(spec, mirror=False, pitch=pitch)
    mould_geom = mould_mod.geometry_for(spec, geom)
    body = body_mod.build(spec, geom)
    mould_info = mould_mod.build(spec, mould_geom)
    scale = checks.scale_of(spec["footprint"])

    body_stl = out / f"{chip_id}_body.stl"
    mould_stl = out / f"{chip_id}_mould.stl"
    body_report = mesh.write_validated(body_stl, body["triangles"], spec["footprint"],
                                       body["z0_mm"], body["z_top_mm"], f"{chip_id}_body")
    mould_report = mesh.write_validated(mould_stl, mould_info["triangles"],
                                        spec["footprint"], mould_info["z0_mm"],
                                        mould_info["z_top_mm"], f"{chip_id}_mould")
    body_report["role"] = body["role"]
    mould_report["role"] = mould_info["role"]

    dxf_path = out / f"{chip_id}.dxf"
    dxf_report = dxf.write_for(dxf_path, spec, geom)

    from . import render
    iso_path, top_path = out / "render_iso.svg", out / "render_top.svg"
    top_report = render.render_top(top_path, spec, geom, scale["warning"])
    iso_report = render.render_iso(iso_path, spec, geom, body, scale["warning"])

    script_path = out / f"{chip_id}_fusion_rebuild.py"
    script_report = fusion.write_script(script_path, spec, geom, body, mould_info,
                                        mould_geom, scale)

    fab_checks = checks.run_all(spec, geom, mould_geom)
    for report in (body_report, mould_report):
        for key, result in report["checks"].items():
            fab_checks.append({
                "check": f"stl_{key}", "passed": result["passed"],
                "detail": f"{report['name']}.stl: {result['detail']}",
                "route": "both", "source": "assay2chip/fabricate/mesh.py validate()",
            })

    files = [
        (body_stl, body["role"]),
        (mould_stl, mould_info["role"]),
        (dxf_path, "closed-polyline cut outline, units declared as mm in the HEADER"),
        (script_path, "Fusion 360 rebuild of both solids"),
        (iso_path, "isometric render"),
        (top_path, "top-view render, 1:1"),
    ]

    doc = manifest.build(
        spec, scale, geom, body, mould_info, fab_checks,
        [body_report, mould_report], files,
        extras={
            "dxf": dxf_report,
            "renders": [top_report, iso_report],
            "fusion_script": script_report,
            "body_stack_gaps": body["stack"]["gaps"],
            "mould_notes": {"mirror": mould_info["mirror_note"],
                            "source": mould_info["source"],
                            "problems": mould_info["problems"]},
        })

    stl_lines = "\n".join(
        f"- **{r['name']}.stl** - {r['triangles']} triangles, {r['volume_mm3']:.3f} mm3: "
        + ", ".join(k.replace("_", " ") for k in r["checks"]) + " - all passed."
        for r in (body_report, mould_report))
    def mark(c):
        if c["passed"]:
            return "PASS"
        return "ADVISORY" if c.get("advisory") else "**FAIL**"

    check_lines = "\n".join(
        f"- {mark(c)} `{c['check']}` - {c['detail']}"
        for c in fab_checks if not c["check"].startswith("stl_"))

    write_text(out / "README.md", README.format(
        chip_id=chip_id, warning=f"**{scale['warning']}**",
        fx=geom["plan"]["fx"], fy=geom["plan"]["fy"],
        body_top=body["z_top_mm"], n_pockets=len(geom["plan"]["features"]),
        depth_um=geom["max_depth_mm"] * 1000, seal=body["stack"]["seal"],
        plate=mould_info["plate_mm"], mirror=mould_info["mirror_note"].capitalize() + ".",
        exag=iso_report["z_exaggeration"], stl_lines=stl_lines, check_lines=check_lines))

    manifest_path = out / "manifest.json"
    write_json(manifest_path, doc)
    doc["out_dir"] = manifest._rel(out)
    return doc
