"""A Fusion 360 script that REBUILDS the chip and its mould as solids, not as meshes.

Pattern follows `chip/components/build_chip.py`: one module-level template string, the
geometry substituted in as JSON, and a `run(context=None)` entry point Fusion calls. The
difference is what it builds. build_chip.py imports placed STLs, which land in Fusion as
mesh bodies you cannot edit; this emits BRep boxes and cylinders through
`TemporaryBRepManager`, exactly as `chip/fusion/chip_from_spec` does, so what opens in
Fusion is real solid geometry - fillet it, add draft to the mould, change the plate
thickness.

Two components per run:

    <id>_body     the chip: a plate with every feature CUT INTO it (difference)
    <id>_mould    the positive tool: the same plate with them RAISED (union), mirrored

Both are rebuilt from the numbers in this file, so the script stands alone: it does not
read the chip spec, the STLs or anything else in the bundle. The features are already
resolved - a routed channel arrives as its individual runs - which is why the rebuild
cannot quietly straighten a channel the router bent.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from assay2chip.lib.io import write_text  # noqa: E402

TEMPLATE = '''"""Fusion 360: rebuild chip {chip_id} and its embossing mould as SOLIDS.

Generated by assay2chip/stages/s11_fabricate.py - do not hand-edit; re-run S11 instead.
Pattern follows chip/components/build_chip.py; the solid building follows
chip/fusion/chip_from_spec/chip_from_spec.py, which is the authority on the mould.

Run it in Fusion: Utilities > Add-Ins > Scripts and Add-Ins (Shift+S) > + > pick this
folder > Run. Or send it through the Fusion MCP execute_code tool.

Builds two components, both in mm at the chip-spec origin (0, 0 at the lower-left corner
of the footprint, z up):

  {chip_id}_body    a {fx:g} x {fy:g} x {body_top:g} mm plate with {n_cut} features CUT into
                    the top face, {depth_um:g} um deep. Channels are OPEN: the lid is a
                    separate film or plate with drilled ports, not modelled here.
  {chip_id}_mould   a {fx:g} x {fy:g} mm, {plate:g} mm plate with the SAME features RAISED
                    {depth_um:g} um - the positive tool for hot embossing.
                    {mirror_note}.

{scale_warning}

NOT MODELLED, on purpose (the spec gives no shape for them): {skipped}
"""

import adsk.core
import adsk.fusion
import traceback

CHIP_ID = {chip_id!r}
FOOTPRINT_MM = ({fx!r}, {fy!r})
BODY_TOP_MM = {body_top!r}        # base + fluidic; z = 0 is the underside of the chip
MOULD_PLATE_MM = {plate!r}        # chip_from_spec.MOULD_BASE_MM
FUSE_MM = {fuse!r}                # raised features start this far inside the plate
OVERCUT_MM = 0.01                 # pockets break the top face cleanly

# Each feature: kind, id, and the numbers to build it with. A box carries its own
# direction, so a diagonal channel run rebuilds at its real angle.
BODY_FEATURES = {body_features}
MOULD_FEATURES = {mould_features}


def _build(features, raised, plate_top, name, design):
    """One component holding one body. `raised` unions the features, else it cuts them."""
    tbm = adsk.fusion.TemporaryBRepManager.get()
    cm = 0.1                                        # the Fusion API works in cm
    fx, fy = FOOTPRINT_MM

    def P(x, y, z):
        return adsk.core.Point3D.create(x * cm, y * cm, z * cm)

    def V(x, y):
        return adsk.core.Vector3D.create(x, y, 0)

    def box(x, y, z0, z1, length, width, d):
        obb = adsk.core.OrientedBoundingBox3D.create(
            P(x, y, (z0 + z1) / 2), V(d[0], d[1]), V(-d[1], d[0]),
            length * cm, width * cm, (z1 - z0) * cm)
        return tbm.createBox(obb)

    def cyl(x, y, z0, z1, r):
        return tbm.createCylinderOrCone(P(x, y, z0), r * cm, P(x, y, z1), r * cm)

    plate = box(fx / 2, fy / 2, 0.0, plate_top, fx, fy, (1.0, 0.0))
    op = (adsk.fusion.BooleanTypes.UnionBooleanType if raised
          else adsk.fusion.BooleanTypes.DifferenceBooleanType)
    for f in features:
        if raised:
            z0, z1 = plate_top - FUSE_MM, plate_top + f["height"]
        else:
            z0, z1 = plate_top - f["height"], plate_top + OVERCUT_MM
        tool = (cyl(f["x"], f["y"], z0, z1, f["r"]) if f["kind"] == "cyl"
                else box(f["x"], f["y"], z0, z1, f["len"], f["wid"], f["dir"]))
        tbm.booleanOperation(plate, tool, op)

    occ = design.rootComponent.occurrences.addNewComponent(adsk.core.Matrix3D.create())
    comp = occ.component
    comp.name = name
    if design.designType == adsk.fusion.DesignTypes.ParametricDesignType:
        base = comp.features.baseFeatures.add()
        base.startEdit()
        comp.bRepBodies.add(plate, base)
        base.finishEdit()
        body = comp.bRepBodies.item(0)
    else:
        body = comp.bRepBodies.add(plate)
    body.name = name
    return body


def run(context=None):
    app = adsk.core.Application.get()
    ui = app.userInterface
    try:
        design = adsk.fusion.Design.cast(app.activeProduct)
        if design is None:
            ui.messageBox("Open a design first (File > New Design).")
            return
        _build(BODY_FEATURES, False, BODY_TOP_MM, CHIP_ID + "_body", design)
        _build(MOULD_FEATURES, True, MOULD_PLATE_MM, CHIP_ID + "_mould", design)
        app.activeViewport.fit()
        ui.messageBox(
            "Rebuilt %s:\\n"
            "  %s_body   %g x %g x %g mm, %d pockets %g um deep\\n"
            "  %s_mould  %g mm plate, the same %d features raised %g um\\n\\n"
            "%s\\n\\n%s"
            % (CHIP_ID, CHIP_ID, FOOTPRINT_MM[0], FOOTPRINT_MM[1], BODY_TOP_MM,
               len(BODY_FEATURES), {depth_um:g},
               CHIP_ID, MOULD_PLATE_MM, len(MOULD_FEATURES), {depth_um:g},
               {mirror_note!r}, {scale_warning!r}),
            "S11 rebuild: " + CHIP_ID)
    except Exception:
        ui.messageBox("rebuild failed:\\n" + traceback.format_exc())


if __name__ == "__main__" and "adsk" not in sys.modules:   # noqa: F821
    print(__doc__)
'''


def _slim(features: list) -> list:
    """Only the keys the rebuild needs, rounded, so the script stays readable."""
    out = []
    for f in features:
        g = {"kind": f["kind"], "id": f["id"], "x": round(f["x"], 4),
             "y": round(f["y"], 4), "height": round(f["height"], 4)}
        if f["kind"] == "cyl":
            g["r"] = round(f["r"], 4)
        else:
            g["len"] = round(f["len"], 4)
            g["wid"] = round(f["wid"], 4)
            g["dir"] = [round(f["dir"][0], 6), round(f["dir"][1], 6)]
        out.append(g)
    return out


def _pretty(features: list) -> str:
    return "[\n" + "".join(f"    {json.dumps(f)},\n" for f in features) + "]"


def write_script(path: Path, spec: dict, geom: dict, body: dict, mould_info: dict,
                 mould_geom: dict, scale: dict) -> dict:
    """Write the rebuild script for one chip. Returns what it contains."""
    body_features = _slim(geom["plan"]["features"])
    mould_features = _slim(mould_geom["plan"]["features"])
    skipped = mould_info["skipped"] or ["nothing"]
    text = TEMPLATE.format(
        chip_id=spec["id"],
        fx=geom["plan"]["fx"], fy=geom["plan"]["fy"],
        body_top=body["z_top_mm"], plate=mould_info["plate_mm"],
        fuse=0.01,
        depth_um=geom["max_depth_mm"] * 1000,
        n_cut=len(body_features),
        mirror_note=mould_info["mirror_note"],
        scale_warning=scale["warning"],
        skipped="; ".join(skipped),
        body_features=_pretty(body_features),
        mould_features=_pretty(mould_features),
    )
    write_text(path, text)
    return {"body_features": len(body_features), "mould_features": len(mould_features),
            "builds": [f"{spec['id']}_body", f"{spec['id']}_mould"],
            "kind": "solid BRep rebuild (not a mesh import)",
            "pattern": "chip/components/build_chip.py"}
